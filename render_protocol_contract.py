#!/usr/bin/env python3
"""Render protocol_contract.json into a human-readable Markdown matrix that
makes cross-implementation disagreements obvious."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
CONTRACT = HERE / "protocol_contract.json"
OUT = HERE / "PROTOCOL_CONTRACT_MATRIX.md"

SOURCES = [
    ("stock", "stock-binary"),
    ("official_web", "official web JS"),
    ("official_live", "official live"),
    ("lobby_monitor", "LobbyMonitor"),
    ("gamewatcher", "GameWatcher"),
    ("dedicated_server", "community server"),
]


def main() -> None:
    doc = json.loads(CONTRACT.read_text(encoding="utf-8"))
    lines: list[str] = []
    lines.append("# BZRNet Protocol Contract Matrix")
    lines.append("")
    lines.append(f"Generated from `protocol_contract.json` "
                 f"(last live verification: {doc.get('last_live_verification')}).")
    lines.append("Do not edit this file by hand; regenerate with "
                 "`python render_protocol_contract.py`.")
    lines.append("")
    lines.append("## Envelope")
    lines.append("")
    for note in doc["envelope"]["notes"]:
        lines.append(f"- {note}")
    lines.append("")
    lines.append("## UDP 1338 (endpoint discovery)")
    lines.append("")
    lines.append(f"- Request: {doc['udp_1338']['request']}")
    lines.append(f"- Response: {doc['udp_1338']['response']}")
    lines.append(f"- Confidence: **{doc['udp_1338']['confidence']}**")
    lines.append("")
    lines.append("## UDP 1339 (relay)")
    lines.append("")
    lines.append(f"- OnP2PRoute payload (live): {doc['udp_1339']['onp2proute_payload_live']}")
    lines.append(f"- Association model: {doc['udp_1339']['association_inference']}")
    lines.append(f"- Same-NAT probe: {doc['udp_1339']['same_nat_probe']}")
    lines.append(f"- Remaining unknown: {doc['udp_1339']['remaining_unknown']}")
    lines.append(f"- Confidence: **{doc['udp_1339']['confidence']}**")
    lines.append("")
    lines.append("## Message records")
    lines.append("")

    for r in doc["records"]:
        flags = r.get("flags", {})
        lines.append(f"### `{r['message']}`  ({r['direction']})")
        lines.append("")
        shape = r.get("content_shape")
        if isinstance(shape, dict):
            lines.append("```json")
            lines.append(json.dumps(shape, indent=2))
            lines.append("```")
        else:
            lines.append(f"- content: {shape}")
        if "lobby_snapshot" in r:
            lines.append("- lobby snapshot keys: " + ", ".join(f"`{k}`" for k in r["lobby_snapshot"]))
            lines.append("- user snapshot keys: " + ", ".join(f"`{k}`" for k in r["user_snapshot"]))
        if "reason_codes" in r:
            lines.append("- reason codes: " + "; ".join(f"`{k}` = {v}" for k, v in r["reason_codes"].items()))
        for key in ("required_fields", "expected_responses"):
            if key in r:
                lines.append(f"- {key}: {', '.join(f'`{v}`' for v in r[key])}")
        lines.append("")
        # Per-source evidence table -- makes disagreements visible.
        lines.append("| source | evidence |")
        lines.append("|---|---|")
        any_row = False
        for flag_key, label in SOURCES:
            ev = r.get(flag_key) or r.get(
                {"stock": "stock_binary", "official_web": "official_web_js",
                 "official_live": "official_live", "lobby_monitor": "lobby_monitor",
                 "gamewatcher": "gamewatcher", "dedicated_server": "dedicated_server"}[flag_key]
            )
            mark = "yes" if flags.get(flag_key) else "-"
            if ev or flags.get(flag_key):
                any_row = True
                ev_text = str(ev).replace("|", "\\|") if ev else ""
                lines.append(f"| {label} | {mark} | {ev_text} |" if False else f"| {label} | {mark} | {ev_text} |")
        if not any_row:
            lines.append("| (none) | - | |")
        lines.append("")
        extra = {k: v for k, v in r.items() if k not in {
            "message", "direction", "content_shape", "flags", "confidence",
            "stock_binary", "official_web_js", "official_live", "lobby_monitor",
            "gamewatcher", "dedicated_server", "lobby_snapshot", "user_snapshot",
            "reason_codes", "required_fields", "expected_responses"}}
        for k, v in extra.items():
            lines.append(f"- **{k}**: {v}")
        lines.append(f"- confidence: **{r.get('confidence', 'UNKNOWN')}**")
        lines.append("")

    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
